import { resolve } from "node:path";
import { format } from "prettier";

const result = await Bun.build({
  entrypoints: ["src/content/curriculum.ts"],
  target: "bun",
  plugins: [
    {
      name: "chapter-raw-fixtures",
      setup(build) {
        build.onResolve({ filter: /\?raw$/ }, ({ path, resolveDir }) => ({
          path: resolve(resolveDir, path.slice(0, -4)),
          namespace: "chapter-raw-fixture",
        }));
        build.onLoad({ filter: /.*/, namespace: "chapter-raw-fixture" }, async ({ path }) => ({
          contents: await Bun.file(path).text(),
          loader: "text",
        }));
      },
    },
  ],
});

if (!result.success) throw new AggregateError(result.logs, "Could not bundle the curriculum");
const bundle = await result.outputs[0].text();
const { chapters } = await import(
  "data:text/javascript;base64," + Buffer.from(bundle).toString("base64")
);
const catalog = chapters.map(({ id, level, title, summary, minutes, blocks }) => ({
  id,
  level,
  title,
  summary,
  minutes,
  available: Boolean(blocks?.length),
}));
const output = await format(
  "// Generated by bun run generate:catalog. Edit chapter sources to change metadata.\n" +
    'import type { ChapterSummary } from "./curriculum-catalog";\n\n' +
    "export const chapters: ChapterSummary[] = " +
    JSON.stringify(catalog) +
    ";\n",
  { parser: "typescript", printWidth: 100 },
);
await Bun.write("src/content/curriculum-catalog.gen.ts", output);
